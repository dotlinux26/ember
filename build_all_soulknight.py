    # Output targets
    props_dir = 'My project/Assets/Resources/Ember/Props'
    interface_dir = 'My project/Assets/Resources/Ember/Interface'
    raw_dir = 'ArtShowcase/raw'
    zoom_dir = 'ArtShowcase/zoomed_8x'
    props_showcase = 'ArtShowcase/props_items'

    os.makedirs(props_dir, exist_ok=True)
    os.makedirs(interface_dir, exist_ok=True)
    os.makedirs(raw_dir, exist_ok=True)
    os.makedirs(zoom_dir, exist_ok=True)
    os.makedirs(props_showcase, exist_ok=True)

    audit_script = 'd:/Ember/.agents/skills/pixel-art/scripts/quality_audit.py'

    for name, img in assets.items():
        w, h = img.size
        # 1. Save to Props
        dest_prop = os.path.join(props_dir, name)
        img.save(dest_prop)

        # 2. Save to Interface if lantern
        if name in ['lantern_inferno.png', 'lantern_relic.png']:
            dest_ui = os.path.join(interface_dir, name)
            img.save(dest_ui)

        # 3. Save to ArtShowcase raw
        dest_raw = os.path.join(raw_dir, name)
        img.save(dest_raw)

        # 4. Save to ArtShowcase props_items
        dest_pi = os.path.join(props_showcase, name)
        img.save(dest_pi)

        # 5. Save 8x zoom using NEAREST filter
        zoomed = img.resize((w * 8, h * 8), Image.NEAREST)
        dest_zoom = os.path.join(zoom_dir, name)
        zoomed.save(dest_zoom)

        # Also save 8x in props_showcase
        base, ext = os.path.splitext(name)
        zoomed.save(os.path.join(props_showcase, f"{base}_8x{ext}"))

        # Run quality audit on generated asset
        cmd = ['python', audit_script, '--image', dest_prop, '--json']
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0 or '"status": "pass"' not in res.stdout:
            print(f"FAILED AUDIT: {name}")
            print(res.stdout)
            sys.exit(1)
        else:
            print(f"PASSED AUDIT: {name} ({w}x{h})")

    # Handle trap.png (approved by user, ensure it exists in showcase and passes audit)
    trap_path = os.path.join(props_dir, 'trap.png')
    if os.path.exists(trap_path):
        trap_img = Image.open(trap_path)
        trap_img.save(os.path.join(raw_dir, 'trap.png'))
        trap_img.save(os.path.join(props_showcase, 'trap.png'))
